"""Write or check docs/api/swig-classes.rst from the built oecluster extension.

The documentation build mocks the compiled extension (docs/conf.py), so
autodoc cannot describe the classes SWIG generates. This script reads them
from the built module instead and writes a page Read the Docs renders as-is.

Run ``python docs/swig_reference.py --write`` (or ``python -m invoke
docs-swig-reference``) after changing a SWIG class; ``--check`` exits 1 when
the committed page differs from what the current build generates.
"""

import argparse
import inspect
import sys
from pathlib import Path

PAGE = Path(__file__).resolve().parent / "api" / "swig-classes.rst"
REGENERATE = "python -m invoke docs-swig-reference"

HEADER = """\
.. Generated by docs/swig_reference.py from the built extension.
   Regenerate with: {regenerate}

SWIG Option and Storage Classes
===============================

These classes are generated by SWIG and are part of the public
:mod:`oecluster` package. Their docstrings are read from the built package:
the SWIG-generated ones come from the C++ documentation, and a few are set in
``oecluster/__init__.py``.

.. highlight:: none
.. py:currentmodule:: oecluster
"""


def swig_classes():
    """Public names on :mod:`oecluster` that are classes SWIG defined."""
    import oecluster
    found = []
    for name in dir(oecluster):
        if name.startswith("_"):
            continue
        obj = getattr(oecluster, name)
        if inspect.isclass(obj) and getattr(obj, "__module__", "") == "oecluster.oecluster":
            found.append((name, obj))
    return sorted(found)


def _signature(obj):
    try:
        return str(inspect.signature(obj))
    except (TypeError, ValueError):
        return ""


def _literal(doc, indent):
    text = inspect.cleandoc(doc) if doc else ""
    if not text:
        return []
    pad = " " * indent
    lines = [pad + "::", ""]
    lines += [(pad + "   " + line).rstrip() for line in text.splitlines()]
    lines.append("")
    return lines


def _properties(cls):
    names = []
    for name in dir(cls):
        if name.startswith("_") or name == "thisown":
            continue
        if isinstance(inspect.getattr_static(cls, name), property):
            names.append(name)
    return sorted(names)


def _methods(cls):
    names = []
    for name in dir(cls):
        if name.startswith("_") or name == "thisown" or hasattr(object, name):
            continue
        if isinstance(inspect.getattr_static(cls, name), property):
            continue
        if callable(getattr(cls, name)):
            names.append(name)
    return sorted(names)


def _unclassified(cls):
    names = []
    for name in dir(cls):
        if name.startswith("_") or name == "thisown" or hasattr(object, name):
            continue
        if isinstance(inspect.getattr_static(cls, name), property):
            continue
        if not callable(getattr(cls, name)):
            names.append(name)
    return sorted(names)


def render():
    """The page text, with \\n line endings and no trailing whitespace."""
    lines = HEADER.format(regenerate=REGENERATE).splitlines()
    lines.append("")
    for name, cls in swig_classes():
        # A SWIG static constant or enum value is neither a property nor
        # callable, so the two passes below would drop it without notice.
        unclassified = _unclassified(cls)
        if unclassified:
            raise RuntimeError(
                f"oecluster.{name} has public attributes this page does not"
                f" describe: {', '.join(unclassified)}")
        lines += [f".. py:class:: {name}{_signature(cls)}", ""]
        lines += _literal(cls.__doc__, 3)
        for prop in _properties(cls):
            lines += [f"   .. py:attribute:: {prop}", ""]
            lines += _literal(inspect.getattr_static(cls, prop).__doc__, 6)
        for method in _methods(cls):
            lines += [f"   .. py:method:: {method}{_signature(getattr(cls, method))}", ""]
            lines += _literal(getattr(cls, method).__doc__, 6)
    return "\n".join(line.rstrip() for line in lines).rstrip() + "\n"


def _normalise(text):
    return "\n".join(line.rstrip() for line in text.replace("\r\n", "\n").splitlines()).rstrip() + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    page = render()
    if args.write:
        PAGE.write_text(page, encoding="utf-8", newline="\n")
        return 0
    current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
    if _normalise(current) != _normalise(page):
        print(f"{PAGE} is out of date with the built extension; run {REGENERATE}.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
